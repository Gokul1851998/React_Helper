import React from 'react';
import { Box, Typography, Paper, CircularProgress, LinearProgress, Stack } from '@mui/material';

const DemoSection = ({ title, children }) => (
  <Box sx={{ mb: 4 }}>
    <Typography variant="h6" sx={{ mb: 2, fontWeight: 600, color: '#1a1a2e' }}>{title}</Typography>
    <Paper sx={{ p: 3, borderRadius: 3, border: '1px solid #e5e7eb' }} elevation={0}>
      {children}
    </Paper>
  </Box>
);

export default function ProgressDemo() {
  const [progress, setProgress] = React.useState(0);

  React.useEffect(() => {
    const timer = setInterval(() => {
      setProgress((prevProgress) => (prevProgress >= 100 ? 0 : prevProgress + 10));
    }, 800);
    return () => clearInterval(timer);
  }, []);

  return (
    <Box>
      <DemoSection title="Circular Progress">
        <Stack spacing={2} direction="row" alignItems="center">
          <CircularProgress />
          <CircularProgress variant="determinate" value={25} />
          <CircularProgress variant="determinate" value={50} />
          <CircularProgress variant="determinate" value={75} />
          <CircularProgress variant="determinate" value={100} />
          <CircularProgress variant="determinate" value={progress} />
        </Stack>
      </DemoSection>

      <DemoSection title="Linear Progress">
        <Stack spacing={2} sx={{ width: '100%' }}>
          <LinearProgress />
          <LinearProgress variant="determinate" value={50} />
          <LinearProgress variant="buffer" value={progress} valueBuffer={progress + 10} />
        </Stack>
      </DemoSection>

      <DemoSection title="With Label">
        <Box sx={{ position: 'relative', display: 'inline-flex' }}>
          <CircularProgress variant="determinate" value={progress} />
          <Box
            sx={{
              top: 0,
              left: 0,
              bottom: 0,
              right: 0,
              position: 'absolute',
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'center',
            }}
          >
            <Typography variant="caption" component="div" color="text.secondary">
              {`${Math.round(progress)}%`}
            </Typography>
          </Box>
        </Box>
      </DemoSection>
    </Box>
  );
}
